// Helper function to get today's soldier
export function getTodaySoldier() {
  const today = new Date();
  const month = today.getMonth() + 1; // JavaScript months are 0-indexed
  const day = today.getDate();
  
  const todaySoldier = soldiers.find(
    (soldier) => soldier.birthMonth === month && soldier.birthDay === day
  );
  
  return todaySoldier || null;
}

